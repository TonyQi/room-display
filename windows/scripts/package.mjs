import fs from 'node:fs';
import core from '../app/core.cjs';
const {copyTree}=core;
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8').replace(/^\uFEFF/,''));
const resources=path.join(root,'runtime-resources');
const electron=path.join(root,'node_modules','electron','dist');
for(const file of [path.join(electron,'electron.exe'),path.join(resources,'jre','bin','java.exe'),path.join(resources,'room-server.jar')])if(!fs.existsSync(file))throw new Error('Missing build dependency: '+file);
const output=path.join(root,'build','RoomDisplay-win32-x64');
if(fs.existsSync(path.join(output,'data')))throw new Error('Build folder contains user data. Do not overwrite it.');
fs.mkdirSync(output,{recursive:true});
copyTree(electron,output);
fs.renameSync(path.join(output,'electron.exe'),path.join(output,'RoomDisplay.exe'));
const app=path.join(output,'resources','app');fs.mkdirSync(app,{recursive:true});
copyTree(path.join(root,'app'),path.join(app,'app'));
fs.writeFileSync(path.join(app,'package.json'),JSON.stringify({name:manifest.name,version:manifest.version,main:'app/main.cjs',private:true},null,2));
copyTree(path.join(resources,'jre'),path.join(output,'resources','jre'));
fs.copyFileSync(path.join(resources,'room-server.jar'),path.join(output,'resources','room-server.jar'));
fs.copyFileSync(path.join(root,'README.md'),path.join(output,'使用说明.md'));
console.log(output);
